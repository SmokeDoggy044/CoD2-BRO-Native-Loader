void set_window_icon(SDL_Window* window) {
    if (!window) return;
    // SDL copies/converts the surface in SDL_SetWindowIcon, so the temporary
    // surface can be destroyed immediately. SDL_PIXELFORMAT_RGBA32 is the
    // byte-order alias for an R,G,B,A byte array.
    SDL_Surface* icon = SDL_CreateSurfaceFrom(kIconWidth, kIconHeight, SDL_PIXELFORMAT_RGBA32,
                                               const_cast<std::uint8_t*>(kIconRgba), kIconWidth * 4);
    if (!icon) return;
    if (!SDL_SetWindowIcon(window, icon)) SDL_ClearError();
    SDL_DestroySurface(icon);
}

